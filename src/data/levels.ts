import type { Bit, Level, TestCase } from '../sim/types';

function truthTable(inputCount: number, fn: (bits: Bit[]) => Bit[]): TestCase[] {
  const rows: TestCase[] = [];
  const total = 1 << inputCount;
  for (let mask = 0; mask < total; mask++) {
    const inputs: Bit[] = [];
    for (let i = 0; i < inputCount; i++) {
      inputs.push(((mask >> (inputCount - 1 - i)) & 1) as Bit);
    }
    rows.push({ inputs, expected: fn(inputs) });
  }
  return rows;
}

